namespace AnyProtocol.Abstraction;

/// <summary>
/// Identifies the available anyprotocol bus values.
/// </summary>
public enum AnyProtocolBusState
{
    /// <summary>
    /// Indicates created.
    /// </summary>
    Created,
    /// <summary>
    /// Indicates starting.
    /// </summary>
    Starting,
    /// <summary>
    /// Indicates started.
    /// </summary>
    Started,
    /// <summary>
    /// Indicates stopping.
    /// </summary>
    Stopping,
    /// <summary>
    /// Indicates stopped.
    /// </summary>
    Stopped,
    /// <summary>
    /// Indicates disposed.
    /// </summary>
    Disposed
}
